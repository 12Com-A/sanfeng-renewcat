    # ------------------------------------------------------------------
    # 审核要求自检
    # ------------------------------------------------------------------
    @classmethod
    def check(cls, title: str, content: str) -> list:
        """按三丰云的投稿要求自检，返回问题列表（空列表表示通过）"""
        problems = []
        text = f"{title or ''}\n{content or ''}"

        for kw in cls.REQUIRED_KEYWORDS:
            if kw not in text:
                problems.append(f"缺少必需关键词: {kw}")
        for word in cls.FORBIDDEN_WORDS:
            if word in text:
                problems.append(f"出现受限词: {word}")
        if cls.SITE_URL not in text:
            problems.append("缺少三丰云官网链接")
        if len(re.sub(r"\s+", "", text)) < 400:
            problems.append("正文过短（要求 50 字以上评测）")
        return problems

    @staticmethod
    def _render(text: str, placeholders: dict) -> str:
        """渲染 {NOW_FULL} / {NOW_DATE} 占位符"""
        for ph, val in placeholders.items():
            text = text.replace(ph, val)
        return text
